public class IT26102744Lab7Q2B {
    public static void main(String[] args) {
        for (int n = 1; n <= 5; n++) {
            System.out.print(n + " - ");
            for (int s = 1; s <= n; s++) {
                System.out.print("* ");
            }
            System.out.println();
        }
    }
}
